"""
Задача: для каждой из первых N записей найти максимум,
затем вывести эти максимумы по убыванию через ';'.

Первая строка входа — сколько записей обработать (N).
Дальше идут записи: в каждой строке числа через пробел.
Записей во входе может быть больше, чем N — лишние не читаем.
"""

n = int(input())  # первая строка — количество записей, которые нужно обработать

maximums = []  # список, куда сложим максимум каждой записи

for _ in range(n):  # читаем РОВНО n строк, даже если во входе их больше
    row = input()            # одна запись, например '4 5 6 7'
    numbers = row.split()    # split() разбивает строку по пробелам -> список строк: ['4', '5', '6', '7']

    # Ищем максимум вручную, циклом: берём первое число за «лучшее» и сравниваем с остальными
    maximum = int(numbers[0])          # int() превращает '4' в число 4
    for part in numbers[1:]:           # numbers[1:] — все элементы, кроме первого
        value = int(part)
        if value > maximum:            # нашли число больше — запоминаем его
            maximum = value

    maximums.append(maximum)  # append() добавляет элемент в конец списка

maximums.sort(reverse=True)  # сортирует список по убыванию (меняет его на месте)

# Собираем ответ: числа -> строки, затем склеиваем через ';'
text_parts = []
for value in maximums:
    text_parts.append(str(value))  # join умеет склеивать только строки
print(';'.join(text_parts))
