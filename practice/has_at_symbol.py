def has_at_symbol(email):
    """
    Проверяет, есть ли в строке символ @.

    Как работает:
    1. Идём по строке слева направо по одному символу.
    2. Номер текущего символа храним в переменной index (0 — первый символ).
    3. Как только встретили '@' — сразу возвращаем True и выходим из функции.
    4. Если цикл дошёл до конца строки, а '@' так и не попался — возвращаем False.
    """
    index = 0  # позиция текущего символа, начинаем с нуля

    # Пока позиция меньше длины строки — символы ещё не закончились
    while index < len(email):
        if email[index] == '@':  # взяли символ по индексу и сравнили с '@'
            return True  # нашли — дальше можно не искать
        index += 1  # переходим к следующему символу (без этого был бы бесконечный цикл)

    # Сюда попали, только если цикл закончился, а '@' не нашли
    return False


