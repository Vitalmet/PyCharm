# Конструкция if __name__ == '__main__' нужна, чтобы этот блок
# выполнялся только при прямом запуске файла, а не при импорте функции.
if __name__ == '__main__':
    print(has_at_symbol('support@example.com'))  # True — символ есть в середине
    print(has_at_symbol('wrong-email'))          # False — символа нет вообще
    print(has_at_symbol('@admin'))               # True — символ в самом начале
    print(has_at_symbol(''))                     # False — пустая строка, цикл не выполнится ни разу

