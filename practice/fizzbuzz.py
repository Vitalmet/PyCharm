def fizzbuzz(n: int) -> str:
    """
    Возвращает строку с числами от 1 до n через пробел, где:
      - вместо чисел, делящихся на 3, стоит 'Fizz'
      - вместо чисел, делящихся на 5, стоит 'Buzz'
      - вместо чисел, делящихся и на 3, и на 5, стоит 'FizzBuzz'

    Пример: fizzbuzz(5) -> '1 2 Fizz 4 Buzz'
    """
    result = ''  # сюда по кусочку собираем ответ

    # range(1, n + 1) даёт числа 1, 2, 3, ..., n (правый конец не включается)
    for number in range(1, n + 1):
        # Сначала решаем, ЧТО написать для этого числа
        if number % 15 == 0:
            # Проверка на 15 идёт первой: 15 делится и на 3, и на 5,
            # иначе для него сработало бы 'Fizz' и до 'FizzBuzz' дело не дошло бы
            word = 'FizzBuzz'
        elif number % 3 == 0:
            word = 'Fizz'
        elif number % 5 == 0:
            word = 'Buzz'
        else:
            word = str(number)  # число превращаем в строку, чтобы приклеить к тексту

        # Теперь добавляем word в ответ.
        # Пробел ставим ПЕРЕД словом и только если это не первый элемент —
        # так в начале и в конце строки лишнего пробела не будет.
        if result != '':
            result += ' '
        result += word

    return result


# Проверка на примерах
if __name__ == '__main__':
    print(fizzbuzz(5))    # 1 2 Fizz 4 Buzz
    print(fizzbuzz(15))   # 1 2 Fizz 4 Buzz Fizz 7 8 Fizz Buzz 11 Fizz 13 14 FizzBuzz

    # repr показывает строку в кавычках — так видно, что лишних пробелов по краям нет
    print(repr(fizzbuzz(5)))
    print(repr(fizzbuzz(1)))   # '1'
    print(repr(fizzbuzz(0)))   # '' — пустая строка, цикл не выполнился ни разу
